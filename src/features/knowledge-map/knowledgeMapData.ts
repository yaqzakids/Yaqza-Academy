import { withMuslimMapAnchors } from './locationLayout'
import type {
  KnowledgeBadge,
  KnowledgeCollectible,
  KnowledgeEra,
  KnowledgeLocationInput,
  KnowledgeRegion,
  RegionalMapConfig,
} from './types'
import { regionalMapForSlug } from './regionalMapData'
import { muslimMapAnchorForRegion } from './worldMapLayout'

function loc(
  id: string,
  title: string,
  regionId: string,
  era: KnowledgeEra,
  opts: Partial<KnowledgeLocationInput> & { description: string },
): KnowledgeLocationInput {
  return {
    id,
    title,
    regionId,
    era,
    type: 'city',
    difficulty: 'discoverer',
    locked: false,
    completed: false,
    collectibleReward: 'Ancient Scroll',
    quizAvailable: true,
    activityAvailable: false,
    ...opts,
  }
}

function region(
  id: string,
  name: string,
  slug: string,
  icon: string,
  description: string,
  locations: KnowledgeLocationInput[],
  status: KnowledgeRegion['status'] = 'in_progress',
  regionalMap?: RegionalMapConfig,
): KnowledgeRegion {
  const located = withMuslimMapAnchors(slug, locations)
  const completed = located.filter((l) => l.completed).length
  return {
    id,
    name,
    slug,
    muslimMapAnchor: muslimMapAnchorForRegion(slug),
    icon,
    description,
    totalLocations: located.length,
    completedLocations: completed,
    status,
    locations: located,
    regionalMap: regionalMap ?? regionalMapForSlug(slug),
  }
}

