A Young Man in Makkah

After growing up under the care of Abu Talib, Muhammad ﷺ entered early manhood in Makkah.

Very little is recorded about these years — there was no writing culture in Makkah, and no one yet knew he would become a prophet.

But one job is clearly documented in Sahih al-Bukhari: Muhammad ﷺ worked as a shepherd.

The Authentic Hadith

The Prophet ﷺ said:

"Allah never sent a prophet except that he was a shepherd."

The companions asked, "Not even you, O Messenger of Allah?"

He replied, "I was. I used to tend the flock of the people of Makkah in return for a small payment."

In another narration, he mentioned tending sheep in the valley of Ajyad, near Makkah.

He also noted that Musa (AS) and Dawud (AS) were sent as prophets while they were shepherds.

Why Shepherding?

Scholars and the Seerah explain several wisdoms:

• Time alone in nature allows reflection on Allah's creation.
• Sheep need guidance and protection — like people need righteous leadership.
• A good shepherd learns gentleness and courage at the same time.
• Earning one's own income teaches independence and humility.
• Starting from the bottom prepares a person to appreciate success later.

Allah could have made the Prophet ﷺ wealthy from childhood. Instead, He chose the most humble, difficult work in Makkah to shape his character.

Surah Ad-Duha

Allah later reminded the Prophet ﷺ in Surah Ad-Duha that He had cared for him through every stage — as an orphan, as one in need, and then as one whom Allah enriched.

The years of shepherding were part of that divine care and preparation.

